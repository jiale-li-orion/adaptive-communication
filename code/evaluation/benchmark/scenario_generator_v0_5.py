#!/usr/bin/env python3
"""Minimal dynamic process generator for Layer-1 v0.5.

The process follows cache06/Astra rather than manufacturing hard labels:
- two report streams share source-shaped cadence;
- obligations overlap in time through stream phase offset;
- all geometry-derived Connecta window STARTS inside the episode are retained; window duration remains abstracted;
- terrestrial service evolves after a shared observed prefix;
- repeated owner reads only reveal sampled current state;
- normal sends generate gateway receipt/final ACK events when service permits.

Labels are produced only by the exact dynamic oracle after generation.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Any
import json

from dynamic_scenario_tree_v0_5 import (
    Bundle,DeliveryEvent,Obligation,OwnerStateEvent,QueryCapability,World,solve,
)
from structural_scaling_v0_3 import CADENCE_S, phase_groups, _slots


@dataclass(frozen=True)
class GeneratedDynamicBundle:
    bundle: Bundle
    coordinates: dict[str,Any]
    exact_solvable: bool | None


def _health_summary(*, recent_forward_ok:bool) -> str:
    # Same proposition shape as the existing gateway primary-health interface:
    # a summary of already-observed forwarding/queue history, not a future service bit.
    if recent_forward_ok:
        return 'last_forward_age_s=180;pending_depth=0;oldest_pending_age_s=0'
    return 'last_forward_age_s=5400;pending_depth=2;oldest_pending_age_s=3600'


def _owner_events(start:int, *, middle_good:bool, late_good:bool) -> tuple[OwnerStateEvent,...]:
    # Sampling at a phase boundary reports the PREVIOUS phase's forwarding history.
    # The initial and first-boundary summaries are identical in all worlds; no query
    # can directly reveal the service state of the phase that is about to begin.
    return (
        OwnerStateEvent(start,'communication.gateway.primary_health',_health_summary(recent_forward_ok=True)),
        OwnerStateEvent(start+CADENCE_S,'communication.gateway.primary_health',_health_summary(recent_forward_ok=True)),
        OwnerStateEvent(start+2*CADENCE_S,'communication.gateway.primary_health',_health_summary(recent_forward_ok=middle_good)),
        OwnerStateEvent(start+3*CADENCE_S,'communication.gateway.primary_health',_health_summary(recent_forward_ok=late_good)),
    )


def _deliveries(obligations:tuple[Obligation,...], sends:tuple[int,...], *, middle_good:bool, late_good:bool) -> tuple[DeliveryEvent,...]:
    rows=[]
    for t in sends:
        phase=0 if t < obligations[0].release_s+CADENCE_S else 1 if t < obligations[0].release_s+2*CADENCE_S else 2
        service_ok=True if phase==0 else middle_good if phase==1 else late_good
        for o in obligations:
            if o.release_s <= t <= o.deadline_s:
                if service_ok:
                    rows.append(DeliveryEvent(t,o.oid,True,t+60,t+180))
                else:
                    rows.append(DeliveryEvent(t,o.oid,False,None,None))
    return tuple(rows)


def build_bundle(*, phase_index:int=0, process_family:str='independent-bits') -> Bundle:
    start,_seed_slots=phase_groups(4,phase_index+1)[phase_index]
    # Two existing monitoring streams use the same 2h source cadence with a
    # controlled 1h phase offset. This changes release timing, not task family.
    obligations=(
        Obligation('A0',start,start+CADENCE_S),
        Obligation('B0',start+CADENCE_S//2,start+CADENCE_S+CADENCE_S//2),
        Obligation('A1',start+CADENCE_S,start+2*CADENCE_S),
        Obligation('B1',start+CADENCE_S+CADENCE_S//2,start+2*CADENCE_S+CADENCE_S//2),
        Obligation('A2',start+2*CADENCE_S,start+3*CADENCE_S),
        Obligation('B2',start+2*CADENCE_S+CADENCE_S//2,start+3*CADENCE_S+CADENCE_S//2),
    )
    # Geometry profile is represented by every recorded window start inside the
    # episode; window duration/service reliability remain controlled abstractions.
    sats=tuple(t for t in _slots() if start <= t <= max(o.deadline_s for o in obligations))

    # One ordinary terrestrial attempt opportunity in each half cadence. The
    # service outcome is generated by the declared finite-state process.
    terr=tuple(start+900+i*(CADENCE_S//2) for i in range(6))
    if process_family=='independent-bits':
        support=((True,True),(True,False),(False,True),(False,False))
    elif process_family=='shifted-window':
        # Separate declared CONTROLLED_STRESS process: exactly one of the two
        # future service epochs carries the finite terrestrial service window.
        # This is not post-hoc deletion of the 00 branch from independent bits.
        support=((True,False),(False,True))
    else:
        raise ValueError(process_family)
    worlds=[]
    for middle_good,late_good in support:
        wid=f'm{int(middle_good)}-l{int(late_good)}'
        reachable=[start,start+CADENCE_S,start+2*CADENCE_S,start+3*CADENCE_S]
        worlds.append(World(
            world_id=wid,
            owner_state_events=_owner_events(start,middle_good=middle_good,late_good=late_good),
            delivery_events=_deliveries(obligations,terr,middle_good=middle_good,late_good=late_good),
            query_reachable_times=tuple(sorted(reachable)),
        ))
    q=QueryCapability(
        query_id='primary_health',
        proposition='communication.gateway.primary_health',
        owner='gateway',
        sample_delay_s=0,
        response_delay_s=120,
        return_path=('gateway_to_center_backhaul',),
        opportunity_dependency=('gateway_reachability',),
    )
    fixed=set(terr)|set(sats)
    fixed.update({start,start+CADENCE_S,start+2*CADENCE_S,start+3*CADENCE_S,start+4*CADENCE_S})
    for o in obligations:
        fixed.add(o.release_s);fixed.add(o.deadline_s)
    for w in worlds:
        for d in w.delivery_events:
            if d.gateway_receipt_at_s is not None:fixed.add(d.gateway_receipt_at_s)
            if d.final_ack_at_s is not None:fixed.add(d.final_ack_at_s)
    return Bundle(
        bundle_id=f'v05-{process_family}-{phase_index}',
        obligations=obligations,
        worlds=tuple(worlds),
        fixed_event_times=tuple(sorted(fixed)),
        terrestrial_send_times=terr,
        satellite_send_times=tuple(sats),
        satellite_budget=2,
        queries=(q,),
    )


def generate(*,phase_limit:int=1,process_families:tuple[str,...]=('independent-bits','shifted-window'),run_exact:bool=False) -> list[GeneratedDynamicBundle]:
    rows=[]
    for i in range(phase_limit):
      for process_family in process_families:
        b=build_bundle(phase_index=i,process_family=process_family)
        exact=solve(b) if run_exact else None
        rows.append(GeneratedDynamicBundle(
            bundle=b,
            coordinates={
                'phase_index':i,
                'streams':2,
                'obligations':len(b.obligations),
                'worlds':len(b.worlds),
                'satellite_budget':b.satellite_budget,
                'process_family':process_family,
                'process':'shared-prefix finite-state terrestrial service',
            },
            exact_solvable=(bool(exact['solvable']) if exact is not None else None),
        ))
    return rows


if __name__=='__main__':
    rows=generate()
    print(json.dumps({
        'bundle_count':len(rows),
        'exact_solvable':sum(r.exact_solvable for r in rows),
        'coordinates':[r.coordinates for r in rows],
    },indent=2,sort_keys=True))
