#!/usr/bin/env python3
"""Dependency-local feasibility frontier for Layer-2 v2.

This module implements the algorithmic object retained by ``cache06.md``:

    obligation <-> communication opportunity conflicts
        -> conditional component certificates
        -> explicit validity domains
        -> event-local invalidation / recomputation
        -> exact fallback only outside certified structure.

It is intentionally separate from Python-level solver micro-optimisation.  The
unit of reuse is a *conflict component* whose future feasibility dependencies
remain unchanged, not a memo entry whose object representation happens to be
cheap.

Hall-deficit structure is generated by bipartite max-flow / residual min-cut
witnesses over obligations and remaining terrestrial opportunity slots.  The
result is therefore a reusable structural certificate rather than a hand-picked
or subset-enumerated conflict label.  The exact Layer-1 transition model remains
the final success authority.
"""
from __future__ import annotations

from collections import deque
from dataclasses import dataclass
from typing import Any, Iterable, Mapping

from exact_reference_oracle_v0_1 import (
    FINAL_ACK_DELAY_S,
    SATELLITE_COMPLETION_DELAY_S,
    LocalState,
    _attempt_lattice,
    _expired,
    _normalize,
    _success,
    _world_map,
)
from v8_policy_baselines_v0_1 import _legal_actions, _step


Slot = tuple[str, str, int]  # kind, window_id, slot_index


def _usage(rows: Iterable[tuple[str, int]]) -> dict[str, int]:
    return {str(k): int(v) for k, v in rows}


def _obligation_rows(bundle: Mapping[str, Any]) -> dict[str, Mapping[str, Any]]:
    return {str(row["obligation_id"]): row for row in bundle["obligations"]}


def _secured_obligations(bundle: Mapping[str, Any], state: LocalState) -> set[str]:
    deadlines = {
        str(row["obligation_id"]): int(row["deadline_s"])
        for row in bundle["obligations"]
    }
    secured = set(state.delivered)
    for pending in state.pending_deliveries:
        if (
            pending.accepted
            and pending.final_ack_at_s is not None
            and pending.final_ack_at_s <= deadlines[pending.obligation_id]
        ):
            secured.add(pending.obligation_id)
    return secured


def _future_terr_candidates(
    bundle: Mapping[str, Any],
    *,
    world_id: str,
    state: LocalState,
    at_s: int,
    obligation_ids: Iterable[str] | None = None,
) -> dict[str, tuple[Slot, ...]]:
    world = _world_map(bundle)[world_id]
    used = _usage(state.terrestrial_used)
    out: dict[str, tuple[Slot, ...]] = {}
    wanted = None if obligation_ids is None else set(obligation_ids)
    for obligation in bundle["obligations"]:
        oid = str(obligation["obligation_id"])
        if wanted is not None and oid not in wanted:
            continue
        if oid in _secured_obligations(bundle, state):
            continue
        deadline = int(obligation["deadline_s"])
        release = int(obligation["release_s"])
        rows: list[Slot] = []
        for window in world["terrestrial_windows"]:
            wid = str(window["window_id"])
            send_at = max(at_s, release, int(window["start_s"]))
            if send_at >= int(window["end_s"]):
                continue
            if send_at + FINAL_ACK_DELAY_S > deadline:
                continue
            start_slot = used.get(wid, 0)
            rows.extend(
                ("T", wid, slot)
                for slot in range(start_slot, int(window["capacity_units"]))
            )
        out[oid] = tuple(rows)
    return out


def _future_sat_candidates(
    bundle: Mapping[str, Any],
    *,
    state: LocalState,
    at_s: int,
    obligation_ids: Iterable[str],
) -> dict[str, tuple[Slot, ...]]:
    obligations = _obligation_rows(bundle)
    used = _usage(state.satellite_used)
    out: dict[str, tuple[Slot, ...]] = {}
    for oid in obligation_ids:
        row = obligations[oid]
        deadline = int(row["deadline_s"])
        release = int(row["release_s"])
        slots: list[Slot] = []
        for window in bundle["public_environment"]["satellite_windows"]:
            wid = str(window["window_id"])
            send_at = max(at_s, release, int(window["start_s"]))
            if send_at >= int(window["end_s"]):
                continue
            if send_at + SATELLITE_COMPLETION_DELAY_S > deadline:
                continue
            start_slot = used.get(wid, 0)
            slots.extend(
                ("S", wid, slot)
                for slot in range(start_slot, int(window["capacity_units"]))
            )
        out[oid] = tuple(slots)
    return out


def _components(candidate_map: Mapping[str, tuple[Slot, ...]]) -> tuple[tuple[str, ...], ...]:
    """Connected components under shared terrestrial opportunities."""

    obligations = sorted(candidate_map)
    adjacency = {oid: set() for oid in obligations}
    slot_owners: dict[Slot, list[str]] = {}
    for oid, slots in candidate_map.items():
        for slot in slots:
            slot_owners.setdefault(slot, []).append(oid)
    for owners in slot_owners.values():
        for left in owners:
            adjacency[left].update(right for right in owners if right != left)

    seen: set[str] = set()
    rows: list[tuple[str, ...]] = []
    for root in obligations:
        if root in seen:
            continue
        stack = [root]
        part: set[str] = set()
        while stack:
            oid = stack.pop()
            if oid in part:
                continue
            part.add(oid)
            seen.add(oid)
            stack.extend(sorted(adjacency[oid] - part))
        rows.append(tuple(sorted(part)))
    return tuple(sorted(rows))


def _hall_deficit(
    obligation_ids: tuple[str, ...],
    candidate_map: Mapping[str, tuple[Slot, ...]],
) -> tuple[int, tuple[tuple[str, ...], ...]]:
    """Exact Hall deficit and one residual min-cut witness.

    Source-to-obligation and slot-to-sink capacities are one.  A maximum
    matching of size ``m`` proves a minimum terrestrial shortage
    ``|O|-m``.  Starting from unmatched obligations in the residual graph and
    following alternating residual edges yields a Hall-deficient set ``U`` and
    its reachable slot neighbourhood ``N(U)``.  For a maximum matching,
    ``|U|-|N(U)|`` equals the component deficiency.
    """

    if not obligation_ids:
        return 0, ()

    source = ("SRC",)
    sink = ("SNK",)
    capacity: dict[Any, dict[Any, int]] = {}

    def edge(left: Any, right: Any, cap: int = 1) -> None:
        capacity.setdefault(left, {})[right] = capacity.setdefault(left, {}).get(right, 0) + cap
        capacity.setdefault(right, {}).setdefault(left, 0)

    all_slots: set[Slot] = set()
    for oid in obligation_ids:
        onode = ("O", oid)
        edge(source, onode, 1)
        for slot in candidate_map.get(oid, ()):
            all_slots.add(slot)
            edge(onode, ("SLOT", slot), 1)
    for slot in sorted(all_slots):
        edge(("SLOT", slot), sink, 1)

    residual = {node: dict(rows) for node, rows in capacity.items()}
    matching = 0
    while True:
        parent: dict[Any, Any | None] = {source: None}
        queue = deque([source])
        while queue and sink not in parent:
            node = queue.popleft()
            for nxt, cap in residual.get(node, {}).items():
                if cap > 0 and nxt not in parent:
                    parent[nxt] = node
                    queue.append(nxt)
        if sink not in parent:
            break
        node = sink
        while parent[node] is not None:
            prev = parent[node]
            residual[prev][node] -= 1
            residual[node][prev] = residual[node].get(prev, 0) + 1
            node = prev
        matching += 1

    deficit = len(obligation_ids) - matching
    if deficit <= 0:
        return 0, ()

    unmatched = [
        ("O", oid)
        for oid in obligation_ids
        if residual[source].get(("O", oid), 0) > 0
    ]
    reachable = set(unmatched)
    queue = deque(unmatched)
    while queue:
        node = queue.popleft()
        for nxt, cap in residual.get(node, {}).items():
            if cap <= 0 or nxt in {source, sink} or nxt in reachable:
                continue
            reachable.add(nxt)
            queue.append(nxt)

    witness_obligations = tuple(
        sorted(node[1] for node in reachable if isinstance(node, tuple) and node[:1] == ("O",))
    )
    witness_slots = {
        node[1]
        for node in reachable
        if isinstance(node, tuple) and node[:1] == ("SLOT",)
    }
    if not witness_obligations:
        # Defensive fallback: the deficiency is still exact from max-flow; a
        # missing witness should never happen for this bipartite construction.
        raise AssertionError("max-flow deficit without residual Hall witness")
    if len(witness_obligations) - len(witness_slots) != deficit:
        raise AssertionError("residual Hall witness does not match maximum-matching deficit")
    return deficit, (witness_obligations,)


def _perfect_information_physical_upper(
    bundle: Mapping[str, Any],
    *,
    at_s: int,
    states: Mapping[str, LocalState],
) -> bool:
    """Optimistic leaf: after an information event, grant hidden-world identity.

    This is intentionally looser than any realizable policy.  Therefore False
    remains a sound impossibility certificate, while True is only UNKNOWN.
    """

    return all(
        build_world_certificate(
            bundle,
            world_id=str(world_id),
            state=state,
            at_s=at_s,
        ).optimistic_feasible
        for world_id, state in states.items()
    )


def information_depth_causal_upper(
    bundle: Mapping[str, Any],
    process: Mapping[str, Any],
    *,
    at_s: int,
    states: Mapping[str, LocalState],
    query_budget: int,
    information_depth: int,
    memo: dict[Any, bool] | None = None,
    metrics: dict[str, int] | None = None,
) -> bool:
    """Sound causal U with horizon measured in evidence transitions.

    SEND/WAIT actions do not consume this horizon.  Only an actual asynchronous
    query/ACK/timeout transition that changes the normalized history consumes
    one information layer.  Once the declared information depth is exhausted,
    the method grants perfect hidden-world information and applies only the
    physical conflict frontier.  The leaf is therefore optimistic and False is
    a sound infeasibility certificate.

    ``information_depth=0`` is the first-observation upper used in the initial
    diagnostic.  Larger values preserve more of the real evidence process while
    still avoiding an arbitrary action-depth bound.
    """

    if information_depth < 0:
        raise ValueError("negative information depth")
    if memo is None:
        memo = {}
    if metrics is None:
        metrics = {}
    before = tuple(sorted(states.items()))
    branches = _normalize(bundle, process, at_s, states)
    metrics["nodes"] = metrics.get("nodes", 0) + 1

    # Any observation split is the information barrier.  Grant perfect
    # information only when the information horizon is exhausted; otherwise
    # continue causally inside every observed branch.
    if len(branches) != 1 or next(iter(branches)) != "same":
        metrics["observation_leaves"] = metrics.get("observation_leaves", 0) + 1
        if information_depth <= 0:
            return all(
                _perfect_information_physical_upper(
                    bundle,
                    at_s=at_s,
                    states=child,
                )
                for child in branches.values()
            )
        return all(
            information_depth_causal_upper(
                bundle,
                process,
                at_s=at_s,
                states=child,
                query_budget=query_budget,
                information_depth=information_depth - 1,
                memo=memo,
                metrics=metrics,
            )
            for child in branches.values()
        )

    support = next(iter(branches.values()))
    after = tuple(sorted(support.items()))
    # A same-valued ACK/query result can update execution/evidence state without
    # partitioning worlds.  It is still an information event; stop the causal
    # prefix here and grant perfect information optimistically.
    if after != before:
        metrics["observation_leaves"] = metrics.get("observation_leaves", 0) + 1
        if information_depth <= 0:
            return _perfect_information_physical_upper(
                bundle,
                at_s=at_s,
                states=support,
            )
        return information_depth_causal_upper(
            bundle,
            process,
            at_s=at_s,
            states=support,
            query_budget=query_budget,
            information_depth=information_depth - 1,
            memo=memo,
            metrics=metrics,
        )

    key = (int(at_s), int(query_budget), int(information_depth), after)
    if key in memo:
        metrics["memo_hits"] = metrics.get("memo_hits", 0) + 1
        return memo[key]
    if any(_expired(bundle, state, at_s) for state in support.values()):
        memo[key] = False
        return False
    if all(_success(bundle, state) for state in support.values()):
        memo[key] = True
        return True

    for action in _legal_actions(bundle, process, support, at_s):
        dq = int(action[0] == "ISSUE_QUERY")
        if dq > query_budget:
            continue
        stepped = _step(bundle, process, support, at_s, action)
        if stepped is None:
            continue
        metrics["action_checks"] = metrics.get("action_checks", 0) + 1
        child, next_t = stepped
        if information_depth_causal_upper(
            bundle,
            process,
            at_s=next_t,
            states=child,
            query_budget=query_budget - dq,
            information_depth=information_depth,
            memo=memo,
            metrics=metrics,
        ):
            memo[key] = True
            return True
    memo[key] = False
    return False


def first_observation_causal_upper(
    bundle: Mapping[str, Any],
    process: Mapping[str, Any],
    *,
    at_s: int,
    states: Mapping[str, LocalState],
    query_budget: int,
    memo: dict[Any, bool] | None = None,
    metrics: dict[str, int] | None = None,
) -> bool:
    """Compatibility wrapper for the information-depth-0 upper bound."""

    return information_depth_causal_upper(
        bundle,
        process,
        at_s=at_s,
        states=states,
        query_budget=query_budget,
        information_depth=0,
        memo=memo,
        metrics=metrics,
    )


def _combined_matching_feasible(
    obligation_ids: tuple[str, ...],
    terr: Mapping[str, tuple[Slot, ...]],
    sat: Mapping[str, tuple[Slot, ...]],
    satellite_budget: int,
) -> bool:
    """Perfect-information physical feasibility for one world.

    Used only as an optimistic structural U.  It ignores observation costs and
    therefore may return True for a causally impossible policy, but False is a
    sound impossibility certificate.
    """

    candidates = {
        oid: tuple(dict.fromkeys((*terr.get(oid, ()), *sat.get(oid, ()))))
        for oid in obligation_ids
    }
    if any(not rows for rows in candidates.values()):
        return False
    order = sorted(obligation_ids, key=lambda oid: (len(candidates[oid]), oid))
    used: set[Slot] = set()

    def rec(index: int, sat_count: int) -> bool:
        if index == len(order):
            return True
        oid = order[index]
        for slot in candidates[oid]:
            if slot in used:
                continue
            next_sat = sat_count + int(slot[0] == "S")
            if next_sat > satellite_budget:
                continue
            used.add(slot)
            if rec(index + 1, next_sat):
                return True
            used.remove(slot)
        return False

    return rec(0, 0)


def _pending_for(state: LocalState, obligation_ids: set[str]) -> tuple[Any, ...]:
    return tuple(
        row
        for row in state.pending_deliveries
        if row.obligation_id in obligation_ids
    )


def _next_pending_event(
    state: LocalState,
    at_s: int,
    *,
    obligation_ids: set[str],
) -> int | None:
    times: list[int] = []
    for pending in state.pending_deliveries:
        if pending.obligation_id not in obligation_ids:
            continue
        for value in (
            pending.gateway_receipt_at_s,
            pending.final_ack_at_s,
            pending.negative_observation_at_s,
        ):
            if value is not None and int(value) > at_s:
                times.append(int(value))
    return min(times) if times else None


@dataclass(frozen=True)
class ComponentCertificate:
    world_id: str
    obligations: tuple[str, ...]
    terrestrial_slots: tuple[Slot, ...]
    satellite_slots: tuple[Slot, ...]
    terrestrial_by_obligation: tuple[tuple[str, tuple[Slot, ...]], ...]
    satellite_by_obligation: tuple[tuple[str, tuple[Slot, ...]], ...]
    hall_deficit: int
    hall_witnesses: tuple[tuple[str, ...], ...]
    dependency_nodes: tuple[str, ...]
    valid_from_s: int
    valid_until_s: int | None
    state_projection: tuple[Any, ...]

    def valid_for(self, *, at_s: int, state: LocalState) -> bool:
        if at_s < self.valid_from_s:
            return False
        if self.valid_until_s is not None and at_s >= self.valid_until_s:
            return False
        oids = set(self.obligations)
        delivered = tuple(sorted(oid for oid in state.delivered if oid in oids))
        pending = _pending_for(state, oids)
        terr_windows = {
            node.split(":", 1)[1]
            for node in self.dependency_nodes
            if node.startswith("T:")
        }
        sat_windows = {
            node.split(":", 1)[1]
            for node in self.dependency_nodes
            if node.startswith("S:")
        }
        projection = (
            delivered,
            pending,
            tuple(sorted((wid, used) for wid, used in state.terrestrial_used if wid in terr_windows)),
            tuple(sorted((wid, used) for wid, used in state.satellite_used if wid in sat_windows)),
            int(state.satellite_budget) if "R:SAT_BUDGET" in self.dependency_nodes else None,
        )
        return projection == self.state_projection


@dataclass(frozen=True)
class WorldConflictCertificate:
    world_id: str
    components: tuple[ComponentCertificate, ...]
    required_backup_lower_bound: int
    optimistic_feasible: bool


@dataclass(frozen=True)
class ConflictFrontierSnapshot:
    at_s: int
    active_world_count: int
    world_certificates: tuple[WorldConflictCertificate, ...]
    worst_case_backup_lower_bound: int
    optimistic_feasible_all_worlds: bool
    conflict_obligations: tuple[str, ...]
    component_count: int


def _component_state_projection(
    state: LocalState,
    *,
    obligations: tuple[str, ...],
    terr_window_ids: set[str],
    sat_window_ids: set[str],
    depends_on_sat_budget: bool,
) -> tuple[Any, ...]:
    oids = set(obligations)
    return (
        tuple(sorted(oid for oid in state.delivered if oid in oids)),
        _pending_for(state, oids),
        tuple(sorted((wid, used) for wid, used in state.terrestrial_used if wid in terr_window_ids)),
        tuple(sorted((wid, used) for wid, used in state.satellite_used if wid in sat_window_ids)),
        int(state.satellite_budget) if depends_on_sat_budget else None,
    )


def _candidate_signature(
    bundle: Mapping[str, Any],
    *,
    world_id: str,
    state: LocalState,
    at_s: int,
    obligations: tuple[str, ...],
    include_satellite: bool,
) -> tuple[Any, ...]:
    terr = _future_terr_candidates(bundle, world_id=world_id, state=state, at_s=at_s)
    sat = (
        _future_sat_candidates(
            bundle,
            state=state,
            at_s=at_s,
            obligation_ids=obligations,
        )
        if include_satellite
        else {}
    )
    return tuple(
        (oid, terr.get(oid, ()), sat.get(oid, ()))
        for oid in obligations
    )


def _valid_until(
    bundle: Mapping[str, Any],
    *,
    world_id: str,
    state: LocalState,
    at_s: int,
    obligations: tuple[str, ...],
    include_satellite: bool,
) -> int | None:
    base = _candidate_signature(
        bundle,
        world_id=world_id,
        state=state,
        at_s=at_s,
        obligations=obligations,
        include_satellite=include_satellite,
    )
    pending = _next_pending_event(
        state,
        at_s,
        obligation_ids=set(obligations),
    )
    for future in _attempt_lattice(bundle):
        future = int(future)
        if future <= at_s:
            continue
        if pending is not None and future >= pending:
            return pending
        if _candidate_signature(
            bundle,
            world_id=world_id,
            state=state,
            at_s=future,
            obligations=obligations,
            include_satellite=include_satellite,
        ) != base:
            return future
    return pending


def build_world_certificate(
    bundle: Mapping[str, Any],
    *,
    world_id: str,
    state: LocalState,
    at_s: int,
) -> WorldConflictCertificate:
    if _expired(bundle, state, at_s):
        return WorldConflictCertificate(
            world_id=world_id,
            components=(),
            required_backup_lower_bound=10**9,
            optimistic_feasible=False,
        )
    return _world_from_components(
        bundle,
        world_id=world_id,
        state=state,
        at_s=at_s,
        components=_build_components_for_obligations(
            bundle,
            world_id=world_id,
            state=state,
            at_s=at_s,
            obligation_ids=None,
        ),
    )


def _build_components_for_obligations(
    bundle: Mapping[str, Any],
    *,
    world_id: str,
    state: LocalState,
    at_s: int,
    obligation_ids: Iterable[str] | None,
) -> tuple[ComponentCertificate, ...]:
    if _expired(bundle, state, at_s):
        return ()
    terr = _future_terr_candidates(
        bundle,
        world_id=world_id,
        state=state,
        at_s=at_s,
        obligation_ids=obligation_ids,
    )
    unresolved = tuple(sorted(terr))
    sat = _future_sat_candidates(
        bundle,
        state=state,
        at_s=at_s,
        obligation_ids=unresolved,
    )
    components: list[ComponentCertificate] = []
    for obligations in _components(terr):
        deficit, witnesses = _hall_deficit(obligations, terr)
        terr_slots = tuple(sorted({slot for oid in obligations for slot in terr.get(oid, ())}))
        raw_sat_slots = tuple(sorted({slot for oid in obligations for slot in sat.get(oid, ())}))
        terr_windows = {slot[1] for slot in terr_slots}
        depends_on_sat = deficit > 0 or any(not terr.get(oid) for oid in obligations)
        sat_slots = raw_sat_slots if depends_on_sat else ()
        sat_windows = {slot[1] for slot in sat_slots}
        nodes = {f"O:{oid}" for oid in obligations}
        nodes.update(f"T:{wid}" for wid in terr_windows)
        if depends_on_sat:
            nodes.add("R:SAT_BUDGET")
            nodes.update(f"S:{wid}" for wid in sat_windows)
        projection = _component_state_projection(
            state,
            obligations=obligations,
            terr_window_ids=terr_windows,
            sat_window_ids=sat_windows,
            depends_on_sat_budget=depends_on_sat,
        )
        components.append(
            ComponentCertificate(
                world_id=world_id,
                obligations=obligations,
                terrestrial_slots=terr_slots,
                satellite_slots=sat_slots,
                terrestrial_by_obligation=tuple(
                    (oid, terr.get(oid, ())) for oid in obligations
                ),
                satellite_by_obligation=tuple(
                    (oid, sat.get(oid, ()) if depends_on_sat else ())
                    for oid in obligations
                ),
                hall_deficit=deficit,
                hall_witnesses=witnesses,
                dependency_nodes=tuple(sorted(nodes)),
                valid_from_s=at_s,
                valid_until_s=_valid_until(
                    bundle,
                    world_id=world_id,
                    state=state,
                    at_s=at_s,
                    obligations=obligations,
                    include_satellite=depends_on_sat,
                ),
                state_projection=projection,
            )
        )
    return tuple(sorted(components, key=lambda row: row.obligations))


def _world_from_components(
    bundle: Mapping[str, Any],
    *,
    world_id: str,
    state: LocalState,
    at_s: int,
    components: Iterable[ComponentCertificate],
) -> WorldConflictCertificate:
    if _expired(bundle, state, at_s):
        return WorldConflictCertificate(
            world_id=world_id,
            components=(),
            required_backup_lower_bound=10**9,
            optimistic_feasible=False,
        )
    rows = tuple(sorted(components, key=lambda row: row.obligations))
    terr: dict[str, tuple[Slot, ...]] = {}
    sat: dict[str, tuple[Slot, ...]] = {}
    for component in rows:
        terr.update(dict(component.terrestrial_by_obligation))
        sat.update(dict(component.satellite_by_obligation))
    unresolved = tuple(sorted(terr))
    backup = sum(row.hall_deficit for row in rows)
    optimistic = _combined_matching_feasible(
        unresolved,
        terr,
        sat,
        int(state.satellite_budget),
    ) if unresolved else True
    return WorldConflictCertificate(
        world_id=world_id,
        components=rows,
        required_backup_lower_bound=backup,
        optimistic_feasible=optimistic,
    )


def _changed_dependency_nodes(old: LocalState, new: LocalState) -> set[str]:
    changed: set[str] = set()
    for oid in set(old.delivered) ^ set(new.delivered):
        changed.add(f"O:{oid}")

    def pending_by_oid(state: LocalState) -> dict[str, tuple[Any, ...]]:
        rows: dict[str, list[Any]] = {}
        for pending in state.pending_deliveries:
            rows.setdefault(pending.obligation_id, []).append(pending)
        return {oid: tuple(values) for oid, values in rows.items()}

    old_pending = pending_by_oid(old)
    new_pending = pending_by_oid(new)
    for oid in set(old_pending) | set(new_pending):
        if old_pending.get(oid) != new_pending.get(oid):
            changed.add(f"O:{oid}")

    old_terr, new_terr = _usage(old.terrestrial_used), _usage(new.terrestrial_used)
    for wid in set(old_terr) | set(new_terr):
        if old_terr.get(wid, 0) != new_terr.get(wid, 0):
            changed.add(f"T:{wid}")

    old_sat, new_sat = _usage(old.satellite_used), _usage(new.satellite_used)
    for wid in set(old_sat) | set(new_sat):
        if old_sat.get(wid, 0) != new_sat.get(wid, 0):
            changed.add(f"S:{wid}")
    if old.satellite_budget != new.satellite_budget:
        changed.add("R:SAT_BUDGET")
    return changed


def aggregate_snapshot(
    *,
    at_s: int,
    worlds: Iterable[WorldConflictCertificate],
) -> ConflictFrontierSnapshot:
    rows = tuple(sorted(worlds, key=lambda row: row.world_id))
    conflict = {
        oid
        for world in rows
        for component in world.components
        if component.hall_deficit > 0
        for oid in component.obligations
    }
    return ConflictFrontierSnapshot(
        at_s=int(at_s),
        active_world_count=len(rows),
        world_certificates=rows,
        worst_case_backup_lower_bound=max(
            (row.required_backup_lower_bound for row in rows),
            default=0,
        ),
        optimistic_feasible_all_worlds=all(row.optimistic_feasible for row in rows),
        conflict_obligations=tuple(sorted(conflict)),
        component_count=sum(len(row.components) for row in rows),
    )


def canonical_snapshot(snapshot: ConflictFrontierSnapshot) -> tuple[Any, ...]:
    return (
        snapshot.at_s,
        snapshot.active_world_count,
        snapshot.worst_case_backup_lower_bound,
        snapshot.optimistic_feasible_all_worlds,
        snapshot.conflict_obligations,
        tuple(
            (
                world.world_id,
                world.required_backup_lower_bound,
                world.optimistic_feasible,
                tuple(
                    (
                        component.obligations,
                        component.terrestrial_slots,
                        component.satellite_slots,
                        component.terrestrial_by_obligation,
                        component.satellite_by_obligation,
                        component.hall_deficit,
                        component.hall_witnesses,
                        component.dependency_nodes,
                        component.valid_until_s,
                    )
                    for component in world.components
                ),
            )
            for world in snapshot.world_certificates
        ),
    )


class IncrementalConflictFrontier:
    """Event-local conflict-component maintenance over one immutable bundle."""

    def __init__(self, bundle: Mapping[str, Any]):
        self.bundle = bundle
        self._cache: dict[tuple[str, tuple[str, ...]], ComponentCertificate] = {}
        self._last_states: dict[str, LocalState] = {}
        self._update_reused_keys: set[tuple[str, tuple[str, ...]]] = set()
        self._update_recomputed_keys: set[tuple[str, tuple[str, ...]]] = set()
        self._update_invalidated_keys: set[tuple[str, tuple[str, ...]]] = set()
        self.metrics = {
            "updates": 0,
            "component_reuses": 0,
            "component_recomputes": 0,
            "world_removals": 0,
            "partition_fallbacks": 0,
        }

    def _world_incremental(
        self,
        *,
        world_id: str,
        state: LocalState,
        at_s: int,
    ) -> WorldConflictCertificate:
        cached_rows = [
            component
            for (wid, _obligations), component in self._cache.items()
            if wid == world_id
        ]
        old_state = self._last_states.get(world_id)
        if old_state is None or not cached_rows:
            rows = _build_components_for_obligations(
                self.bundle,
                world_id=world_id,
                state=state,
                at_s=at_s,
                obligation_ids=None,
            )
            for row in rows:
                self._cache[(world_id, row.obligations)] = row
                self._update_recomputed_keys.add((world_id, row.obligations))
            self.metrics["component_recomputes"] += len(rows)
            self._last_states[world_id] = state
            return _world_from_components(
                self.bundle,
                world_id=world_id,
                state=state,
                at_s=at_s,
                components=rows,
            )

        changed_nodes = _changed_dependency_nodes(old_state, state)
        reused: list[ComponentCertificate] = []
        invalidated: list[ComponentCertificate] = []
        for component in cached_rows:
            key = (world_id, component.obligations)
            touches_event = bool(set(component.dependency_nodes) & changed_nodes)
            if not touches_event and component.valid_for(at_s=at_s, state=state):
                reused.append(component)
                self.metrics["component_reuses"] += 1
                self._update_reused_keys.add(key)
            else:
                invalidated.append(component)
                self._update_invalidated_keys.add(key)

        affected_obligations = {
            oid
            for component in invalidated
            for oid in component.obligations
        }
        rebuilt: tuple[ComponentCertificate, ...] = ()
        if affected_obligations:
            rebuilt = _build_components_for_obligations(
                self.bundle,
                world_id=world_id,
                state=state,
                at_s=at_s,
                obligation_ids=affected_obligations,
            )
            self.metrics["component_recomputes"] += len(rebuilt)

        # Under the current v0.2 transition model, future opportunity edges can
        # disappear through time/resource consumption but never appear from a
        # previously unrelated component.  Assert that no recomputed component
        # now shares a terrestrial slot with a reused component; if that
        # monotonic-partition assumption is violated, conservatively rebuild the
        # whole world instead of risking an unsound local update.
        reused_slots = {
            slot
            for component in reused
            for slot in component.terrestrial_slots
        }
        rebuilt_slots = {
            slot
            for component in rebuilt
            for slot in component.terrestrial_slots
        }
        if reused_slots & rebuilt_slots:
            rows = _build_components_for_obligations(
                self.bundle,
                world_id=world_id,
                state=state,
                at_s=at_s,
                obligation_ids=None,
            )
            self.metrics["partition_fallbacks"] += 1
            self.metrics["component_recomputes"] += len(rows)
            self._update_reused_keys.difference_update(
                key for key in tuple(self._update_reused_keys) if key[0] == world_id
            )
            reused = []
            rebuilt = rows

        for component in invalidated:
            self._cache.pop((world_id, component.obligations), None)
        for component in rebuilt:
            self._cache[(world_id, component.obligations)] = component
            self._update_recomputed_keys.add((world_id, component.obligations))

        active_components = tuple(sorted((*reused, *rebuilt), key=lambda row: row.obligations))
        self._last_states[world_id] = state
        return _world_from_components(
            self.bundle,
            world_id=world_id,
            state=state,
            at_s=at_s,
            components=active_components,
        )

    def update(
        self,
        *,
        at_s: int,
        states: Mapping[str, LocalState],
    ) -> tuple[ConflictFrontierSnapshot, dict[str, Any]]:
        before = dict(self.metrics)
        self._update_reused_keys.clear()
        self._update_recomputed_keys.clear()
        self._update_invalidated_keys.clear()
        self.metrics["updates"] += 1
        active = set(states)
        cached_worlds = {key[0] for key in self._cache}
        removed = cached_worlds - active
        self.metrics["world_removals"] += len(removed)
        # Do not destroy dormant certificates when a lawful observation narrows
        # support.  Real execution support is monotone-shrinking; retaining the
        # dormant entry is harmless and also keeps exhaustive branch audits from
        # charging artificial rebuilds when they traverse sibling observations.
        rows = [
            self._world_incremental(world_id=wid, state=state, at_s=at_s)
            for wid, state in sorted(states.items())
        ]
        delta = {
            key: self.metrics[key] - before[key]
            for key in self.metrics
        }
        delta.update(
            {
                "reused_component_keys": tuple(sorted(self._update_reused_keys)),
                "recomputed_component_keys": tuple(sorted(self._update_recomputed_keys)),
                "invalidated_component_keys": tuple(sorted(self._update_invalidated_keys)),
                "removed_world_ids": tuple(sorted(removed)),
            }
        )
        return aggregate_snapshot(at_s=at_s, worlds=rows), delta

    def full_rebuild(
        self,
        *,
        at_s: int,
        states: Mapping[str, LocalState],
    ) -> ConflictFrontierSnapshot:
        return aggregate_snapshot(
            at_s=at_s,
            worlds=(
                build_world_certificate(
                    self.bundle,
                    world_id=wid,
                    state=state,
                    at_s=at_s,
                )
                for wid, state in sorted(states.items())
            ),
        )

    @staticmethod
    def materialized_context(snapshot: ConflictFrontierSnapshot) -> dict[str, Any]:
        """Model-facing derived feasibility context.

        Internal certificates may use the same declared possible-world process
        as the observation-matched planner/oracle, but raw future window
        identities, per-world witnesses and certificate invalidation times are
        never exposed to the policy.  The policy receives only robust
        support-level consequences of that model.
        """

        hall_rows: dict[tuple[str, ...], int] = {}
        for world in snapshot.world_certificates:
            for component in world.components:
                if component.hall_deficit > 0:
                    hall_rows[component.obligations] = max(
                        hall_rows.get(component.obligations, 0),
                        component.hall_deficit,
                    )
        return {
            "schema_version": "layer2-v2-conflict-frontier-0.1",
            "time_s": snapshot.at_s,
            "compatible_support_count": snapshot.active_world_count,
            "optimistic_completion_possible": snapshot.optimistic_feasible_all_worlds,
            "minimum_backup_lower_bound": snapshot.worst_case_backup_lower_bound,
            "conflict_obligations": list(snapshot.conflict_obligations),
            "conflict_components": [
                {
                    "obligations": list(obligations),
                    "minimum_backup_lower_bound": deficit,
                }
                for obligations, deficit in sorted(hall_rows.items())
            ],
            "hidden_future_window_identity_exposed": False,
            "oracle_witness_exposed": False,
            "surface": "DERIVED_SUPPORT_LEVEL_FEASIBILITY",
        }
