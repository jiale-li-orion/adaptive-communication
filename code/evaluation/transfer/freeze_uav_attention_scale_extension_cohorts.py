#!/usr/bin/env python3
"""Freeze external-paper-matched and hard-feasible N=10 scale cohorts.

Two method-independent cohorts are materialized:

``paper_matched_50``
    Exact layout seeds generated by the external repository's published
    ``evaluate_policy(..., episodes=50, seed=999)`` protocol.

``constructive_100``
    First 100 seeds (ascending) from a 0..999 scan where at least one official
    released heuristic already completes all customers, returns to depot, has
    zero tardiness and takes no infeasible action.  No Future-Choice method or
    exact continuation oracle participates in selection.
"""
from __future__ import annotations

from hashlib import sha256
import json
import os
from pathlib import Path
import subprocess
import sys

import numpy as np


ROOT = Path(__file__).resolve().parents[3]
EXT = ROOT / "local_research/external/uav-attention-routing"
TRANSFER = ROOT / "code/evaluation/transfer"
if str(TRANSFER) not in sys.path:
    sys.path.insert(0, str(TRANSFER))

from run_uav_attention_future_choice_lu import N_SETTINGS, _install_gymnasium_shim  # noqa: E402


OUT = ROOT / "results/transfer/uav-attention-n10-scale-extension-cohorts.json"


def _git_head(path: Path) -> str | None:
    try:
        return subprocess.check_output(
            ["git", "-C", str(path), "rev-parse", "HEAD"], text=True
        ).strip()
    except Exception:
        return None


def _sha(path: Path) -> str:
    return sha256(path.read_bytes()).hexdigest()


def main() -> int:
    for name in ("OPENBLAS_NUM_THREADS", "OMP_NUM_THREADS", "MKL_NUM_THREADS", "NUMEXPR_NUM_THREADS"):
        os.environ.setdefault(name, "1")
    _install_gymnasium_shim()
    sys.path.insert(0, str(EXT))
    from src.env import SingleUAVConfig, SingleUAVEnv  # type: ignore
    from src.heuristic import (  # type: ignore
        BatteryAwareNearestNeighbour,
        GreedyDeadlineBatteryHeuristic,
        NearestDeadlineFirstHeuristic,
        NearestNeighbourHeuristic,
    )

    mission_time, dmin, dmax = N_SETTINGS[10]

    def cfg():
        return SingleUAVConfig(
            num_customers=10,
            num_chargers=1,
            mission_time=mission_time,
            deadline_min=dmin,
            deadline_max=dmax,
            reward_mode="completion_ratio",
        )

    classes = {
        "nearest_neighbour": NearestNeighbourHeuristic,
        "nearest_deadline": NearestDeadlineFirstHeuristic,
        "greedy_deadline_battery": GreedyDeadlineBatteryHeuristic,
        "battery_aware_nn": BatteryAwareNearestNeighbour,
    }

    # External paper protocol: evaluate_policy creates a fresh env for every
    # episode and uses rng.integers(0,1_000_000) as the layout reset seed.
    rng = np.random.default_rng(999)
    paper50 = [int(rng.integers(0, 1_000_000)) for _ in range(50)]

    paper50_per = {name: [] for name in classes}
    paper50_constructive = []
    paper50_witnesses: dict[str, dict[str, list[int]]] = {}
    for seed in paper50:
        good = []
        for name, cls in classes.items():
            env = SingleUAVEnv(cfg())
            obs, info = env.reset(seed=seed)
            policy = cls()
            actions = []
            while True:
                action = int(policy.act(env, obs, info))
                actions.append(action)
                obs, _r, terminated, truncated, info = env.step(action)
                if terminated or truncated:
                    break
            ok = bool(
                info["completed"]
                and info["returned_to_depot"]
                and float(info["ep_tardiness"]) <= 1e-9
                and int(info["ep_infeasible"]) == 0
            )
            if ok:
                paper50_per[name].append(seed)
                good.append(name)
                paper50_witnesses.setdefault(str(seed), {})[name] = actions
        if good:
            paper50_constructive.append(seed)

    per = {name: [] for name in classes}
    cohort = []
    witnesses: dict[str, dict[str, list[int]]] = {}
    for seed in range(1000):
        good = []
        for name, cls in classes.items():
            env = SingleUAVEnv(cfg())
            obs, info = env.reset(seed=seed)
            policy = cls()
            actions = []
            while True:
                action = int(policy.act(env, obs, info))
                actions.append(action)
                obs, _r, terminated, truncated, info = env.step(action)
                if terminated or truncated:
                    break
            ok = bool(
                info["completed"]
                and info["returned_to_depot"]
                and float(info["ep_tardiness"]) <= 1e-9
                and int(info["ep_infeasible"]) == 0
            )
            if ok:
                per[name].append(seed)
                good.append(name)
                witnesses.setdefault(str(seed), {})[name] = actions
        if good:
            cohort.append(seed)

    if len(cohort) < 100:
        raise AssertionError(f"need >=100 constructive seeds, got {len(cohort)}")
    selected100 = cohort[:100]

    official_eval = EXT / "src/heuristic.py"
    exp3 = EXT / "experiments/exp3_attention_scaling.py"
    payload = {
        "stage": "UAV_ATTENTION_N10_SCALE_EXTENSION_COHORT_FREEZE",
        "external_repo": "mdehghani86/uav-attention-routing",
        "external_commit": _git_head(EXT),
        "setting": {
            "num_customers": 10,
            "mission_time": mission_time,
            "deadline_min": dmin,
            "deadline_max": dmax,
        },
        "paper_matched_50": {
            "episodes": 50,
            "evaluation_rng_seed": 999,
            "layout_seeds": paper50,
            "protocol": "exact seed sequence generated by external src.heuristic.evaluate_policy",
            "constructive_hard_feasible_lower_bound_count": len(paper50_constructive),
            "constructive_hard_feasible_lower_bound_rate": len(paper50_constructive) / 50.0,
            "constructive_seeds": paper50_constructive,
            "official_heuristic_success_counts": {
                k: len(v) for k, v in paper50_per.items()
            },
            "constructive_witness_actions": paper50_witnesses,
        },
        "constructive_scan": {
            "seed_scan": [0, 999],
            "scanned": 1000,
            "constructive_count": len(cohort),
            "constructive_rate": len(cohort) / 1000.0,
            "constructive_seeds": cohort,
            "official_heuristic_success_counts": {k: len(v) for k, v in per.items()},
        },
        "constructive_100": {
            "count": 100,
            "selection": "first 100 constructive seeds in ascending seed order",
            "seeds": selected100,
            "constructive_witness_actions": {
                str(seed): witnesses[str(seed)] for seed in selected100
            },
            "future_choice_method_used_for_selection": False,
            "exact_oracle_used_for_selection": False,
        },
        "source_digests": {
            "external_src_heuristic_py": _sha(official_eval),
            "external_exp3_attention_scaling_py": _sha(exp3),
        },
        "checks": {
            "paper_matched_count_50": len(paper50) == 50,
            "paper_layout_seeds_unique": len(set(paper50)) == 50,
            "paper_constructive_seeds_subset": set(paper50_constructive) <= set(paper50),
            "constructive_at_least_100": len(cohort) >= 100,
            "constructive_100_unique": len(set(selected100)) == 100,
            "constructive_100_is_prefix_of_method_independent_scan": selected100 == cohort[:100],
        },
        "claim_boundary": [
            "The paper-matched panel aligns episode count and layout-seed generation with the external repository's published evaluation protocol; it does not reproduce the unavailable learned checkpoint.",
            "The constructive-100 cohort is intentionally conservative: every selected seed is already solved zero-tardiness by at least one official ordinary heuristic.",
            "Seeds not selected by the constructive scan may still be hard-feasible; the selector is a lower-bound feasibility filter, not an exact prevalence estimator."
        ],
    }
    if not all(payload["checks"].values()):
        raise AssertionError(payload["checks"])
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(json.dumps({
        "out": str(OUT),
        "paper50_first5": paper50[:5],
        "constructive_count": len(cohort),
        "constructive100_last_seed": selected100[-1],
        "by_heuristic": {k: len(v) for k, v in per.items()},
    }, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
