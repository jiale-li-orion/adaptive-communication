#!/usr/bin/env python3
"""Formal pre-model probe for the action-conditioned context selector.

The experiment deliberately uses localized O2 because action scope is smaller
than the network while the physical task/simulator already exist.  The method
and its full-dump ablation receive identical candidate-plan generation; only the
evidence selector differs.
"""
from __future__ import annotations

import argparse
from datetime import UTC, datetime
import hashlib
import json
from pathlib import Path
import statistics
import sys

HERE = Path(__file__).resolve().parent
CODE = HERE.parents[1]
ROOT = CODE.parent
for p in (
    CODE,
    CODE / "v3joint",
    CODE / "instance",
    CODE / "monitoring",
    CODE / "physics",
    CODE / "runtime",
    CODE / "experiments",
    CODE / "analysis",
):
    if str(p) not in sys.path:
        sys.path.insert(0, str(p))

from agentic_communication.episodes import o2_localized_risk_escalation_task  # noqa: E402
from agentic_communication.metrics import physical_signature  # noqa: E402
from agentic_communication.model_protocol import protocol_bytes  # noqa: E402
from agentic_communication.planner import (  # noqa: E402
    ActionConditionedReferencePlannerConsumer,
    DeterministicComplyPlannerConsumer,
)
from agentic_communication.replay import audit_trace, frozen_r1_inputs, load_trace  # noqa: E402
from agentic_communication.run import run_agentic_episode, run_reference_comply  # noqa: E402


OUT = ROOT / "results" / "agentic" / "action-conditioned-context-localized-o2-v1"
ARMS = {
    "task_conditioned": ("task_conditioned", DeterministicComplyPlannerConsumer),
    "full_dump": ("full_dump", DeterministicComplyPlannerConsumer),
    "action_conditioned": ("action_conditioned", ActionConditionedReferencePlannerConsumer),
    "action_candidates_full_dump": (
        "action_candidates_full_dump",
        ActionConditionedReferencePlannerConsumer,
    ),
}


def dump(path: Path, value) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for block in iter(lambda: fh.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", default="0,1,2,3,4")
    ap.add_argument("--out", default=str(OUT))
    args = ap.parse_args()
    seeds = [int(x) for x in args.seeds.split(",") if x.strip()]
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    task = o2_localized_risk_escalation_task()

    contract = {
        "experiment_id": "action-conditioned-context-localized-o2-v1",
        "method": "action-conditioned candidate-plan -> evidence-dependency -> context selection",
        "task": task.model_dump(mode="json"),
        "seeds": seeds,
        "arms": list(ARMS),
        "primary_method_comparison": ["action_conditioned", "action_candidates_full_dump"],
        "secondary_context_comparisons": ["task_conditioned", "full_dump"],
        "success_condition": (
            "action_conditioned and action_candidates_full_dump preserve paired physical behavior; "
            "with identical candidate-plan generation, action_conditioned selects fewer evidence rows "
            "and materializes fewer bytes than candidate+FullDump"
        ),
        "claim_ceiling": (
            "Deterministic method-path and model-input differentiation only. This probe does not claim "
            "real-model decision improvement or a communication-service gain."
        ),
    }
    dump(out / "experiment_contract.json", contract)
    dump(
        out / "source_manifest.json",
        {
            "schema_revision": "1",
            "operational_task_source_refs": list(task.source_refs),
            "system_model": "research/SYSTEM-MODEL-v1.md",
            "experiment_design": "research/EXPERIMENT-DESIGN-v1.md",
            "method_implementation": "code/agentic_communication/action_context.py",
            "runtime_implementation": "code/agentic_communication/context_runtime.py",
            "physical_substrate": [
                "code/instance/",
                "code/v3joint/",
            ],
            "claim_boundary": (
                "Source/task/system ownership only. Numeric method results are generated by this runner "
                "from the frozen simulator and must not be inferred from the source manifest."
            ),
        },
    )

    rows: list[dict] = []
    with (out / "per_seed_results.jsonl").open("w", encoding="utf-8") as fh:
        for seed in seeds:
            reference, _, _ = run_reference_comply(seed=seed, operational_task=task)
            ref_sig = physical_signature(reference)
            for arm, (mode, consumer_cls) in ARMS.items():
                consumer = consumer_cls()
                result, policy, _, _ = run_agentic_episode(
                    seed=seed,
                    operational_task=task,
                    context_mode=mode,
                    planner_consumer=consumer,
                )
                trace = out / "traces" / f"seed-{seed:03d}-{arm}.jsonl"
                policy.trace.write_jsonl(trace)
                replay = audit_trace(trace, context_mode=mode)
                records = frozen_r1_inputs(load_trace(trace))
                pbytes = [len(protocol_bytes(row.assembly)) for row in records]
                metrics = result["agentic"]["agent_metrics"]
                row = {
                    "seed": seed,
                    "arm": arm,
                    "context_mode": mode,
                    "physical_equal_reference": physical_signature(result) == ref_sig,
                    "replay_passed": bool(replay.get("passed")),
                    "contexts": metrics["contexts"],
                    "mean_selected_evidence": metrics["mean_selected_evidence"],
                    "mean_materialized_bytes": metrics["mean_materialized_bytes"],
                    "mean_protocol_bytes": statistics.fmean(pbytes) if pbytes else 0.0,
                    "max_protocol_bytes": max(pbytes) if pbytes else 0,
                    "trace": str(trace.relative_to(ROOT)),
                    "trace_sha256": sha256(trace),
                }
                rows.append(row)
                fh.write(json.dumps(row, ensure_ascii=False) + "\n")

    by_arm: dict[str, dict] = {}
    for arm in ARMS:
        rr = [row for row in rows if row["arm"] == arm]
        by_arm[arm] = {
            "n": len(rr),
            "all_physical_equal": all(row["physical_equal_reference"] for row in rr),
            "all_replay_passed": all(row["replay_passed"] for row in rr),
            "mean_selected_evidence": statistics.fmean(row["mean_selected_evidence"] for row in rr),
            "mean_materialized_bytes": statistics.fmean(row["mean_materialized_bytes"] for row in rr),
            "mean_protocol_bytes": statistics.fmean(row["mean_protocol_bytes"] for row in rr),
        }
    ac = by_arm["action_conditioned"]
    af = by_arm["action_candidates_full_dump"]
    aggregate = {
        "n_seeds": len(seeds),
        "arms": by_arm,
        "method_vs_candidate_full_dump": {
            "selected_evidence_delta": ac["mean_selected_evidence"] - af["mean_selected_evidence"],
            "materialized_bytes_delta": ac["mean_materialized_bytes"] - af["mean_materialized_bytes"],
            "protocol_bytes_delta": ac["mean_protocol_bytes"] - af["mean_protocol_bytes"],
            "selected_evidence_reduction_fraction": (
                1.0 - ac["mean_selected_evidence"] / af["mean_selected_evidence"]
                if af["mean_selected_evidence"] else 0.0
            ),
            "protocol_bytes_reduction_fraction": (
                1.0 - ac["mean_protocol_bytes"] / af["mean_protocol_bytes"]
                if af["mean_protocol_bytes"] else 0.0
            ),
        },
    }
    dump(out / "aggregate.json", aggregate)
    audit = {
        "status": "PASS",
        "all_physical_equal": all(x["all_physical_equal"] for x in by_arm.values()),
        "all_replay_passed": all(x["all_replay_passed"] for x in by_arm.values()),
        "candidate_controlled_evidence_contraction": (
            ac["mean_selected_evidence"] < af["mean_selected_evidence"]
        ),
        "candidate_controlled_materialization_contraction": (
            ac["mean_materialized_bytes"] < af["mean_materialized_bytes"]
        ),
        "candidate_controlled_protocol_contraction": (
            ac["mean_protocol_bytes"] < af["mean_protocol_bytes"]
        ),
    }
    audit["status"] = "PASS" if all(v is True for k, v in audit.items() if k != "status") else "FAIL"
    dump(out / "audit.json", audit)
    dump(
        out / "run_manifest.json",
        {
            "generated_at": datetime.now(UTC).isoformat(),
            "runner": "code/experiments/agentic/run_action_conditioned_context_probe.py",
            "seeds": seeds,
            "result_hashes": {
                name: sha256(out / name)
                for name in (
                    "experiment_contract.json",
                    "source_manifest.json",
                    "per_seed_results.jsonl",
                    "aggregate.json",
                    "audit.json",
                )
            },
        },
    )
    print(json.dumps({"audit": audit, "aggregate": aggregate}, ensure_ascii=False, indent=2))
    return 0 if audit["status"] == "PASS" else 1


if __name__ == "__main__":
    raise SystemExit(main())
